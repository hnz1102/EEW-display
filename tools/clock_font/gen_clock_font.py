#!/usr/bin/env python3
"""Pre-render the idle clock's date characters as anti-aliased alpha bitmaps.

The ESP32 build has only bitmap fonts (stair-stepped when enlarged), so the
few characters the clock's date needs are rendered here from an outline font
and embedded as 8-bit coverage maps.

    python3 tools/clock_font/gen_clock_font.py [path/to/font.ttf]

Writes src/clock_font_data.rs (included by src/display_pages.rs).
Default font: DejaVu Sans Condensed Bold (Bitstream Vera / DejaVu license,
free to embed and redistribute).
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed-Bold.ttf"
CHARS = "0123456789/ADEFHIMNORSTUW"   # digits, '/', and the letters of MON..SUN
SIZES = [("CLOCK_FONT_L", 40), ("CLOCK_FONT_S", 18)]  # (name, pixel size)
OUT = Path(__file__).resolve().parents[2] / "src" / "clock_font_data.rs"


def render(size):
    font = ImageFont.truetype(FONT, size)
    # Common vertical extent over all glyphs, measured from the baseline.
    tops, bots = [], []
    for ch in CHARS:
        l, t, r, b = font.getbbox(ch, anchor="ls")
        tops.append(t)
        bots.append(b)
    top, bot = min(tops), max(bots)
    h = bot - top
    glyphs = []
    for ch in CHARS:
        w = round(font.getlength(ch))
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((0, -top), ch, font=font, fill=255, anchor="ls")
        glyphs.append((ch, w, bytes(im.getdata())))
    return h, glyphs


def main():
    out = [
        "// Generated by tools/clock_font/gen_clock_font.py — do not edit.",
        f"// Source font: {Path(FONT).name} (DejaVu fonts license: free to embed).",
        "// Anti-aliased glyphs for the idle clock's date: 8-bit coverage, row-major.",
        "",
        "/// An anti-aliased font: every glyph is `h` rows high.",
        "struct AaFont { h: i32, glyphs: &'static [(char, i32, &'static [u8])] }",
        "",
    ]
    for name, size in SIZES:
        h, glyphs = render(size)
        out.append(f"static {name}: AaFont = AaFont {{ h: {h}, glyphs: &[")
        for ch, w, data in glyphs:
            lit = "".join(f"\\x{b:02x}" for b in data)
            out.append(f"    ({ch!r}, {w}, b\"{lit}\"),")
        out.append("]};")
        out.append("")
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
